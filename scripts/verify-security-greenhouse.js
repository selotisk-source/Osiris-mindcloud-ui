"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const server = fs.readFileSync(path.join(__dirname, "..", "frontend-server.js"), "utf8");
const greenhouse = fs.readFileSync(path.join(__dirname, "..", "tillvaxthuset.html"), "utf8");
const policy = fs.readFileSync(path.join(__dirname, "..", "SECURITY_BASELINE.md"), "utf8");
assert.match(server, /function rateLimit\(/, "API rate limiter must exist");
assert.match(server, /res\.writeHead\(429/, "rate limit must return HTTP 429");
assert.match(server, /retry-after/i, "rate limit must set Retry-After");
assert.match(server, /createHash\("sha256"\)/, "bearer token identity must be hashed");
assert.match(server, /function setSecurityHeaders\(/, "security headers must exist");
assert.match(server, /urlLength > 4096/, "API request target must be bounded");
assert.match(policy, /shared limiter/i, "production shared-rate-limit requirement must be documented");
assert.match(greenhouse, /function renderLesson\(/, "lesson interactions must be wired");
assert.match(greenhouse, /session\.xp=\(session\.xp\|\|0\)\+25/, "correct answers must award XP");
assert.match(greenhouse, /session\.completed\.push\(index\)/, "completed lessons must be tracked");
assert.match(greenhouse, /name\.length>40/, "display name must have a length limit");
console.log("Security baseline and Tillväxthuset smoke checks passed.");
